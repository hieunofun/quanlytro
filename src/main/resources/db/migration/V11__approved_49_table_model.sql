 IF a.meter_id<>b.meter_id OR a.observed_at>=b.observed_at OR a.reading_value>b.reading_value THEN
 RAISE EXCEPTION 'Consumption endpoints must increase on the same meter' USING ERRCODE='23514'; END IF;

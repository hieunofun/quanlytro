 AND tstzrange(s.service_start,s.service_end,'[)') && tstzrange(a.observed_at,b.observed_at,'[)')) THEN
 RAISE EXCEPTION 'Consumption interval overlaps an existing interval' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;

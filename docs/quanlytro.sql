notification_id bigint NOT NULL REFERENCES notifications(id), user_id bigint NOT NULL REFERENCES users(id), read_at timestamptz,
UNIQUE(notification_id,user_id)
);

-- Tệp và metadata, không chứa file thay đổi dưới cùng key
CREATE TABLE stored_files (

-- Thiết kế mục tiêu bước 1–2: 17 bảng nghiệp vụ, PostgreSQL 16+.
-- Chạy trên database trống, sau đó chạy database-rules.sql.
-- Không phải migration cho backend prototype V1–V9.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) NOT NULL UNIQUE CHECK (btrim(username) <> ''),
  password_hash varchar(255) NOT NULL,
  role varchar(20) NOT NULL CHECK (role IN ('ADMIN','STAFF','TENANT')),
  status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','LOCKED','INACTIVE')),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE properties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_code varchar(30) NOT NULL UNIQUE CHECK (btrim(property_code) <> ''),
  name varchar(150) NOT NULL CHECK (btrim(name) <> ''),
  address text NOT NULL CHECK (btrim(address) <> ''),
  status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
  meter_cutoff_day smallint NOT NULL DEFAULT 28 CHECK (meter_cutoff_day BETWEEN 1 AND 31),
  invoice_issue_day smallint NOT NULL DEFAULT 1 CHECK (invoice_issue_day BETWEEN 1 AND 28),
  alert_threshold_percentage numeric(7,2) NOT NULL DEFAULT 50 CHECK (alert_threshold_percentage > 0),
  alert_history_months smallint NOT NULL DEFAULT 3 CHECK (alert_history_months BETWEEN 1 AND 12),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rooms (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id bigint NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
  floor_number smallint NOT NULL DEFAULT 1 CHECK (floor_number >= 0),
  room_code varchar(30) NOT NULL CHECK (btrim(room_code) <> ''),
  base_price numeric(12,2) NOT NULL CHECK (base_price >= 0),
  max_occupants smallint NOT NULL DEFAULT 2 CHECK (max_occupants > 0),
  area_sqm numeric(6,2) CHECK (area_sqm > 0),
  operational_status varchar(20) NOT NULL DEFAULT 'AVAILABLE'
    CHECK (operational_status IN ('AVAILABLE','MAINTENANCE')),
  description text NOT NULL DEFAULT '',
  internal_note text NOT NULL DEFAULT '',
  UNIQUE (property_id, room_code)
);
CREATE TABLE employee_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  property_id bigint NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
  assigned_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (user_id, property_id)
);
CREATE TABLE tenant_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint UNIQUE REFERENCES users(id) ON DELETE SET NULL,
  full_name varchar(100) NOT NULL CHECK (btrim(full_name) <> ''),
  identity_number varchar(20) UNIQUE,
  phone varchar(20),
  email varchar(100),
  date_of_birth date,
  hometown varchar(150),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE contracts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_code varchar(50) NOT NULL UNIQUE,
  room_id bigint NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
  primary_tenant_id bigint NOT NULL REFERENCES tenant_profiles(id) ON DELETE RESTRICT,
  start_date date NOT NULL,
  end_date date NOT NULL,
  actual_checkout_date date,
  rental_price numeric(12,2) NOT NULL CHECK (rental_price >= 0),
  deposit_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (deposit_amount >= 0),
  payment_cycle_day smallint NOT NULL DEFAULT 5 CHECK (payment_cycle_day BETWEEN 1 AND 28),
  status varchar(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('PENDING','ACTIVE','TERMINATED','CANCELLED')),
  terms text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (start_date < end_date),
  CHECK (actual_checkout_date IS NULL OR
    (actual_checkout_date > start_date AND actual_checkout_date <= end_date)),
  CHECK ((status = 'TERMINATED') = (actual_checkout_date IS NOT NULL)),
  CONSTRAINT ex_contract_room_period EXCLUDE USING gist (
    room_id WITH =,
    daterange(start_date, COALESCE(actual_checkout_date,end_date),'[)') WITH &&
  ) WHERE (status <> 'CANCELLED')
);
CREATE TABLE contract_members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id bigint NOT NULL REFERENCES contracts(id) ON DELETE RESTRICT,
  tenant_id bigint NOT NULL REFERENCES tenant_profiles(id) ON DELETE RESTRICT,
  relationship varchar(50),
  effective_from date NOT NULL,
  effective_to date,
  CHECK (effective_to IS NULL OR effective_from < effective_to),
  UNIQUE (contract_id, tenant_id, effective_from),
  CONSTRAINT ex_member_period EXCLUDE USING gist (
    contract_id WITH =, tenant_id WITH =,
    daterange(effective_from,effective_to,'[)') WITH &&
  )
);
CREATE TABLE service_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_code varchar(30) NOT NULL UNIQUE,
  name varchar(100) NOT NULL CHECK (btrim(name) <> ''),
  calculation_type varchar(20) NOT NULL CHECK (calculation_type IN ('METER_BASED','PER_ROOM','PER_PERSON')),
  unit_name varchar(30) NOT NULL,
  is_mandatory boolean NOT NULL DEFAULT true
);
CREATE TABLE service_price_configs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id bigint NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
  service_item_id bigint NOT NULL REFERENCES service_items(id) ON DELETE RESTRICT,
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  effective_from date NOT NULL,
  UNIQUE (property_id, service_item_id, effective_from)
);
CREATE TABLE meter_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id bigint NOT NULL REFERENCES contracts(id) ON DELETE RESTRICT,
  service_item_id bigint NOT NULL REFERENCES service_items(id) ON DELETE RESTRICT,
  billing_period date NOT NULL CHECK (extract(day FROM billing_period) = 1),
  old_index numeric(10,2) NOT NULL CHECK (old_index >= 0),
  new_index numeric(10,2) NOT NULL CHECK (new_index >= old_index),
  reading_date date NOT NULL,
  recorded_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  CHECK (reading_date >= billing_period AND reading_date < billing_period + interval '1 month'),
  UNIQUE (contract_id, billing_period, service_item_id)
);
CREATE TABLE consumption_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meter_reading_id bigint NOT NULL UNIQUE REFERENCES meter_readings(id) ON DELETE CASCADE,
  baseline_average numeric(12,2) NOT NULL CHECK (baseline_average > 0),
  applied_threshold_percentage numeric(7,2) NOT NULL CHECK (applied_threshold_percentage > 0),
  history_months smallint NOT NULL CHECK (history_months BETWEEN 1 AND 12),
  status varchar(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','CONFIRMED','DISMISSED')),
  checked_by bigint REFERENCES users(id) ON DELETE RESTRICT,
  checked_at timestamptz,
  note text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((status = 'PENDING' AND checked_by IS NULL AND checked_at IS NULL) OR
    (status <> 'PENDING' AND checked_by IS NOT NULL AND checked_at IS NOT NULL))
);
CREATE TABLE invoices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_code varchar(50) NOT NULL UNIQUE,
  contract_id bigint NOT NULL REFERENCES contracts(id) ON DELETE RESTRICT,
  billing_period date NOT NULL CHECK (extract(day FROM billing_period) = 1),
  issue_date date NOT NULL,
  due_date date NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','ISSUED')),
  is_settlement boolean NOT NULL DEFAULT false,
  issued_at timestamptz,
  CHECK (due_date >= issue_date),
  CHECK ((status = 'DRAFT' AND issued_at IS NULL) OR (status = 'ISSUED' AND issued_at IS NOT NULL)),
  UNIQUE (contract_id, billing_period)
);
CREATE TABLE invoice_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id bigint NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  service_item_id bigint REFERENCES service_items(id) ON DELETE RESTRICT,
  meter_reading_id bigint UNIQUE REFERENCES meter_readings(id) ON DELETE RESTRICT,
  item_name_snapshot varchar(100) NOT NULL,
  unit_name_snapshot varchar(30) NOT NULL,
  unit_price_snapshot numeric(12,2) NOT NULL CHECK (unit_price_snapshot >= 0),
  quantity integer,
  CHECK ((meter_reading_id IS NOT NULL AND service_item_id IS NULL AND quantity IS NULL) OR
    (meter_reading_id IS NULL AND quantity IS NOT NULL AND quantity > 0)),
  UNIQUE (invoice_id, service_item_id)
);
CREATE UNIQUE INDEX uq_invoice_room_line ON invoice_items(invoice_id)
  WHERE service_item_id IS NULL AND meter_reading_id IS NULL;
CREATE TABLE payment_transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id bigint NOT NULL REFERENCES invoices(id) ON DELETE RESTRICT,
  transaction_code varchar(50) NOT NULL UNIQUE,
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  payment_method varchar(30) NOT NULL CHECK (payment_method IN ('CASH','BANK_TRANSFER_MANUAL','DEPOSIT_OFFSET','OTHER')),
  payment_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  received_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  notes text
);
CREATE TABLE checkout_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id bigint NOT NULL UNIQUE REFERENCES contracts(id) ON DELETE RESTRICT,
  deposit_snapshot numeric(12,2) NOT NULL CHECK (deposit_snapshot >= 0),
  outstanding_snapshot numeric(14,2) NOT NULL CHECK (outstanding_snapshot >= 0),
  damage_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (damage_amount >= 0),
  settled_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  settled_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes text
);
CREATE TABLE maintenance_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id bigint NOT NULL REFERENCES contracts(id) ON DELETE RESTRICT,
  submitted_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  assigned_to bigint REFERENCES users(id) ON DELETE RESTRICT,
  title varchar(150) NOT NULL CHECK (btrim(title) <> ''),
  description text NOT NULL CHECK (btrim(description) <> ''),
  priority varchar(20) NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('URGENT','NORMAL','LOW')),
  status varchar(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','ACCEPTED','IN_PROGRESS','COMPLETED')),
  expected_date date NOT NULL,
  actual_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK (actual_cost >= 0),
  progress_note text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE maintenance_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maintenance_request_id bigint NOT NULL REFERENCES maintenance_requests(id) ON DELETE CASCADE,
  url text NOT NULL CHECK (btrim(url) <> ''),
  uploaded_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (maintenance_request_id, url)
);
CREATE INDEX idx_rooms_property ON rooms(property_id);
CREATE INDEX idx_contract_tenant ON contracts(primary_tenant_id);
CREATE INDEX idx_member_tenant ON contract_members(tenant_id);
CREATE INDEX idx_invoice_contract ON invoices(contract_id);
CREATE INDEX idx_payment_invoice ON payment_transactions(invoice_id);
CREATE INDEX idx_maintenance_contract ON maintenance_requests(contract_id);
CREATE INDEX idx_alert_status ON consumption_alerts(status);

COMMENT ON TABLE users IS 'Tài khoản đăng nhập; thông tin người cư trú lưu tại tenant_profiles.';
COMMENT ON TABLE tenant_profiles IS 'Hồ sơ dùng chung cho đại diện và thành viên; một người có nhiều lần cư trú.';
COMMENT ON TABLE contract_members IS 'Liên kết N–N người thuê–hợp đồng, chỉ lưu người ở cùng; đại diện nằm tại contracts.primary_tenant_id.';
COMMENT ON TABLE invoice_items IS 'Dòng đo đếm lấy lượng từ chỉ số đã khóa; dòng còn lại lưu ngày/ngày-người. Thành tiền tính qua view.';
COMMENT ON COLUMN invoice_items.quantity IS 'Ngày ở/ngày-người cho khoản thu tháng; NULL khi tham chiếu chỉ số đo đếm.';
COMMENT ON TABLE checkout_records IS 'Snapshot cọc và nợ trước cấn; số quyết toán tính qua view, có thể âm.';
COMMENT ON COLUMN rooms.operational_status IS 'Tình trạng khai thác; trạng thái đang thuê suy ra từ hợp đồng.';

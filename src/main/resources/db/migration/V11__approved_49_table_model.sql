-- V11: approved 49-table application. V1-V10 are intentionally unchanged.
-- Atomic archival/import. Never infer an unrecorded deposit receipt or signature.
DO $$ DECLARE t record; n integer; BEGIN
 IF EXISTS(SELECT 1 FROM pg_namespace WHERE nspname='model_v10') THEN RAISE EXCEPTION 'model_v10 already exists; investigate previous cutover'; END IF;
 SELECT count(*) INTO n FROM pg_tables WHERE schemaname='public' AND tablename<>'flyway_schema_history';
 IF n<>17 THEN RAISE EXCEPTION 'Expected V10 with 17 application tables, got %',n; END IF;
 CREATE SCHEMA model_v10;
 FOR t IN SELECT viewname FROM pg_views WHERE schemaname='public' LOOP
 EXECUTE format('ALTER VIEW public.%I SET SCHEMA model_v10',t.viewname); END LOOP;
 FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='public' AND tablename<>'flyway_schema_history' LOOP
 EXECUTE format('ALTER TABLE public.%I SET SCHEMA model_v10',t.tablename); END LOOP;
END $$;

-- Approved application model V11: 49 tables. PostgreSQL 18.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Tài khoản đăng nhập
CREATE TABLE users (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
username varchar(50) NOT NULL UNIQUE CHECK (btrim(username)<>''),
password_hash varchar(255) NOT NULL,
role varchar(20) NOT NULL CHECK(role IN ('ADMIN','STAFF','TENANT')),
status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','LOCKED','INACTIVE')),
created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Hồ sơ người, độc lập với vai trò ký/liên hệ/cư trú
CREATE TABLE tenant_profiles (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id bigint UNIQUE REFERENCES users(id),
full_name varchar(150) NOT NULL CHECK(btrim(full_name)<>''),
identity_number varchar(30) UNIQUE CHECK(identity_number IS NULL OR btrim(identity_number)<>''),
phone varchar(30), email varchar(150), date_of_birth date, hometown text,
created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Khu nhà; một chủ nhà trong phạm vi ứng dụng
CREATE TABLE properties (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
property_code varchar(30) NOT NULL UNIQUE, name varchar(150) NOT NULL, address text NOT NULL,
status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE')),
meter_cutoff_day smallint NOT NULL DEFAULT 28 CHECK(meter_cutoff_day BETWEEN 1 AND 31),
invoice_issue_day smallint NOT NULL DEFAULT 1 CHECK(invoice_issue_day BETWEEN 1 AND 28),
collection_timing varchar(20) NOT NULL DEFAULT 'IN_ADVANCE' CHECK(collection_timing IN ('IN_ADVANCE','IN_ARREARS')),
created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Phòng và sức chứa; giá/trạng thái được lấy từ nguồn theo thời gian
CREATE TABLE rooms (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
property_id bigint NOT NULL REFERENCES properties(id), floor_number smallint NOT NULL DEFAULT 1 CHECK(floor_number>=0),
room_code varchar(30) NOT NULL, max_occupants smallint NOT NULL DEFAULT 2 CHECK(max_occupants>0),
area_sqm numeric(8,2) CHECK(area_sqm>0), description text NOT NULL DEFAULT '', internal_note text NOT NULL DEFAULT '',
opened_on date NOT NULL DEFAULT CURRENT_DATE, retired_on date CHECK(retired_on>=opened_on),
UNIQUE(property_id,room_code)
);

-- Phân công đúng khu hoặc đúng phòng, có hiệu lực
CREATE TABLE employee_assignments (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id bigint NOT NULL REFERENCES users(id), property_id bigint REFERENCES properties(id), room_id bigint REFERENCES rooms(id),
assigned_at timestamptz NOT NULL DEFAULT clock_timestamp(), revoked_at timestamptz,
CHECK(num_nonnulls(property_id,room_id)=1), CHECK(revoked_at IS NULL OR revoked_at>=assigned_at)
);

-- Ủy quyền hành động và hạn mức trong phân công
CREATE TABLE staff_permission_grants (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
assignment_id bigint NOT NULL REFERENCES employee_assignments(id), action_code varchar(40) NOT NULL,
amount_limit numeric(14,2) CHECK(amount_limit>=0), expires_at timestamptz,
granted_by bigint NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
UNIQUE(assignment_id,action_code),
CHECK(action_code IN ('MANAGE','BILLING','RECEIVE','REFUND','DEPOSIT_OFFSET','TRANSFER','ADJUST','WAIVE_DEPOSIT','MAINTENANCE'))
);

-- Mã khôi phục băm, dùng một lần
CREATE TABLE password_reset_tokens (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id bigint NOT NULL REFERENCES users(id), token_hash varchar(64) NOT NULL UNIQUE,
issued_by bigint NOT NULL REFERENCES users(id), expires_at timestamptz NOT NULL, used_at timestamptz,
attempts smallint NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
created_at timestamptz NOT NULL DEFAULT clock_timestamp(), CHECK(expires_at>created_at)
);

-- Lịch sử thao tác; không lưu thông tin xác thực
CREATE TABLE audit_events (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
actor_user_id bigint REFERENCES users(id), actor_type varchar(10) NOT NULL DEFAULT 'USER' CHECK(actor_type IN ('USER','SYSTEM')),
action varchar(80) NOT NULL, resource_type varchar(80) NOT NULL, resource_id varchar(100),
before_data jsonb, after_data jsonb, reason text, recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK((actor_type='USER')=(actor_user_id IS NOT NULL))
);

-- Giá niêm yết; không tự thay giá hợp đồng
CREATE TABLE room_price_history (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
room_id bigint NOT NULL REFERENCES rooms(id), effective_from date NOT NULL,
amount numeric(14,2) NOT NULL CHECK(amount>=0), recorded_by bigint REFERENCES users(id),
created_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(room_id,effective_from)
);

-- Khoảng sẵn sàng, chuẩn bị, bảo trì hoặc ngừng khai thác
CREATE TABLE room_operating_periods (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
room_id bigint NOT NULL REFERENCES rooms(id), valid_from timestamptz NOT NULL, valid_to timestamptz,
status varchar(20) NOT NULL CHECK(status IN ('READY','TURNOVER','MAINTENANCE','INACTIVE')),
recorded_by bigint REFERENCES users(id), note text,
CHECK(valid_to IS NULL OR valid_to>valid_from),
EXCLUDE USING gist(room_id WITH =,tstzrange(valid_from,valid_to,'[)') WITH &&)
);

-- Danh mục tiện nghi và hạng mục tài sản
CREATE TABLE asset_types (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code varchar(40) NOT NULL UNIQUE, name varchar(150) NOT NULL, unit_name varchar(30) NOT NULL DEFAULT 'Cái'
);

-- Tài sản có mã hoặc nhóm số lượng
CREATE TABLE assets (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
asset_type_id bigint NOT NULL REFERENCES asset_types(id), asset_code varchar(50) NOT NULL UNIQUE,
quantity numeric(12,2) NOT NULL DEFAULT 1 CHECK(quantity>0),
status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','RETIRED')), note text
);

-- Vị trí tài sản theo thời gian; phòng hoặc khu vực chung
CREATE TABLE asset_placements (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
asset_id bigint NOT NULL REFERENCES assets(id), room_id bigint REFERENCES rooms(id), property_id bigint REFERENCES properties(id),
valid_from timestamptz NOT NULL, valid_to timestamptz, recorded_by bigint REFERENCES users(id),
CHECK(num_nonnulls(room_id,property_id)=1), CHECK(valid_to IS NULL OR valid_to>valid_from),
EXCLUDE USING gist(asset_id WITH =,tstzrange(valid_from,valid_to,'[)') WITH &&)
);

-- Giữ chỗ có thời hạn và điều kiện hủy
CREATE TABLE reservations (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
room_id bigint NOT NULL REFERENCES rooms(id), tenant_id bigint REFERENCES tenant_profiles(id),
reservation_code varchar(60) NOT NULL UNIQUE, contact_name varchar(150), contact_phone varchar(30),
start_date date NOT NULL, end_date date NOT NULL, expires_at timestamptz NOT NULL,
status varchar(20) NOT NULL DEFAULT 'HELD' CHECK(status IN ('HELD','CONVERTED','CANCELLED','EXPIRED')),
conditions text NOT NULL DEFAULT '', created_by bigint REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(start_date<end_date), CHECK(tenant_id IS NOT NULL OR btrim(coalesce(contact_name,''))<>'')
);

-- Một phòng cố định, liên kết hợp đồng kế tiếp khi chuyển phòng/thay bên thuê
CREATE TABLE contracts (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
room_id bigint NOT NULL REFERENCES rooms(id), reservation_id bigint UNIQUE REFERENCES reservations(id),
previous_contract_id bigint REFERENCES contracts(id), continuation_reason varchar(30),
contract_code varchar(60) NOT NULL UNIQUE, start_date date NOT NULL,
reconciliation_status varchar(20) NOT NULL DEFAULT 'VERIFIED' CHECK(reconciliation_status IN ('VERIFIED','PENDING')),
status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PENDING','ACTIVE','ENDED','CANCELLED')),
created_by bigint REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(previous_contract_id IS NULL OR previous_contract_id<>id),
CHECK((previous_contract_id IS NULL)=(continuation_reason IS NULL)),
CHECK(continuation_reason IS NULL OR continuation_reason IN ('ROOM_TRANSFER','PARTY_CHANGE','CONTINUATION'))
);

-- Vai trò bên ký; không tự coi người ký là người ở
CREATE TABLE contract_parties (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), tenant_id bigint NOT NULL REFERENCES tenant_profiles(id),
party_role varchar(30) NOT NULL CHECK(party_role IN ('PRIMARY','GUARANTOR','WITNESS')),
effective_from date NOT NULL, effective_to date, agreement_note text NOT NULL DEFAULT '',
CHECK(effective_to IS NULL OR effective_to>effective_from), UNIQUE(contract_id,tenant_id,party_role,effective_from)
);

-- Liên hệ và quyền được cấp độc lập với bên ký
CREATE TABLE contract_contacts (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), tenant_id bigint NOT NULL REFERENCES tenant_profiles(id),
contact_role varchar(20) NOT NULL DEFAULT 'PRIMARY' CHECK(contact_role IN ('PRIMARY','BACKUP')),
effective_from date NOT NULL, effective_to date, can_view_billing boolean NOT NULL DEFAULT false,
authorized_by bigint REFERENCES users(id), CHECK(effective_to IS NULL OR effective_to>effective_from),
EXCLUDE USING gist(contract_id WITH =,daterange(effective_from,effective_to,'[)') WITH &&) WHERE(contact_role='PRIMARY')
);

-- Tất cả người thực ở kể cả người ký nếu có ở
CREATE TABLE contract_residencies (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), tenant_id bigint NOT NULL REFERENCES tenant_profiles(id),
effective_from date NOT NULL, effective_to date, relationship varchar(50), recorded_by bigint REFERENCES users(id),
CHECK(effective_to IS NULL OR effective_to>effective_from),
EXCLUDE USING gist(contract_id WITH =,tenant_id WITH =,daterange(effective_from,effective_to,'[)') WITH &&)
);

-- Bản điều kiện và phụ lục đã duyệt có hiệu lực, không sửa đè
CREATE TABLE contract_terms (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), version_no integer NOT NULL CHECK(version_no>0),
effective_from date NOT NULL, lease_end date NOT NULL, rental_price numeric(14,2) NOT NULL CHECK(rental_price>=0),
deposit_required numeric(14,2) NOT NULL DEFAULT 0 CHECK(deposit_required>=0),
payment_day smallint NOT NULL DEFAULT 5 CHECK(payment_day BETWEEN 1 AND 28),
collection_timing varchar(20) NOT NULL DEFAULT 'IN_ADVANCE' CHECK(collection_timing IN ('IN_ADVANCE','IN_ARREARS')),
terms text NOT NULL DEFAULT '', signed_at timestamptz, approved_by bigint REFERENCES users(id),
origin varchar(20) NOT NULL DEFAULT 'NATIVE' CHECK(origin IN ('NATIVE','LEGACY_V10')),
status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','APPROVED')),
created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(lease_end>effective_from), CHECK(status<>'APPROVED' OR origin='LEGACY_V10' OR (signed_at IS NOT NULL AND approved_by IS NOT NULL)),
UNIQUE(contract_id,version_no)
);

-- Quyền sử dụng thực tế không tự kết thúc khi hết hạn giấy
CREATE TABLE room_possessions (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), taken_at timestamptz NOT NULL, returned_at timestamptz,
recorded_by bigint REFERENCES users(id), note text,
CHECK(returned_at IS NULL OR returned_at>taken_at),
EXCLUDE USING gist(contract_id WITH =,tstzrange(taken_at,returned_at,'[)') WITH &&)
);

-- Đề nghị trả, thay/hủy không tự giải phóng phòng
CREATE TABLE move_out_notices (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), supersedes_notice_id bigint REFERENCES move_out_notices(id),
requested_date date NOT NULL, reason text NOT NULL DEFAULT '',
status varchar(20) NOT NULL DEFAULT 'SUBMITTED' CHECK(status IN ('SUBMITTED','APPROVED','CANCELLED','SUPERSEDED')),
submitted_by bigint NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(supersedes_notice_id IS NULL OR supersedes_notice_id<>id)
);

-- Biên bản nhận/trả/giao trách nhiệm
CREATE TABLE handovers (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), possession_id bigint REFERENCES room_possessions(id),
handover_code varchar(60) NOT NULL UNIQUE, handover_type varchar(20) NOT NULL CHECK(handover_type IN ('MOVE_IN','MOVE_OUT','RESPONSIBILITY')),
occurred_at timestamptz NOT NULL, status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','CONFIRMED','UNCONFIRMED')),
given_by bigint REFERENCES users(id), received_by_tenant_id bigint REFERENCES tenant_profiles(id),
confirmed_by bigint REFERENCES users(id), confirmed_at timestamptz, note text,
CHECK(status<>'CONFIRMED' OR (confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL))
);

-- Snapshot đồ vật và tình trạng lúc giao
CREATE TABLE handover_items (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
handover_id bigint NOT NULL REFERENCES handovers(id), asset_placement_id bigint REFERENCES asset_placements(id),
line_no integer NOT NULL CHECK(line_no>0), item_name_snapshot varchar(150) NOT NULL,
quantity numeric(12,2) NOT NULL CHECK(quantity>=0), condition_note text NOT NULL, note text,
UNIQUE(handover_id,line_no)
);

-- Vi phạm và kết quả xử lý, không tự sinh khoản phạt
CREATE TABLE contract_violations (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), violation_type varchar(50) NOT NULL, description text NOT NULL,
occurred_on date NOT NULL, status varchar(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','HANDLING','RESOLVED','DISMISSED')),
resolution_note text, created_by bigint NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Snapshot quyết toán trước cấn, không coi tính ra là đã hoàn
CREATE TABLE checkout_records (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), return_handover_id bigint REFERENCES handovers(id),
billing_end date NOT NULL, status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','APPROVED','LEGACY_RECORDED')),
deposit_snapshot numeric(14,2) NOT NULL DEFAULT 0 CHECK(deposit_snapshot>=0),
advance_snapshot numeric(14,2) NOT NULL DEFAULT 0 CHECK(advance_snapshot>=0),
outstanding_snapshot numeric(14,2) NOT NULL DEFAULT 0 CHECK(outstanding_snapshot>=0),
approved_by bigint REFERENCES users(id), approved_at timestamptz, notes text,
CHECK(status<>'APPROVED' OR (approved_by IS NOT NULL AND approved_at IS NOT NULL))
);

-- Danh mục dịch vụ; không thay đăng ký dịch vụ
CREATE TABLE service_items (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
service_code varchar(30) NOT NULL UNIQUE, name varchar(100) NOT NULL, unit_name varchar(30) NOT NULL,
calculation_type varchar(20) NOT NULL CHECK(calculation_type IN ('METER_BASED','PER_ROOM','PER_PERSON','PER_UNIT','ONE_TIME')),
is_mandatory boolean NOT NULL DEFAULT false, is_active boolean NOT NULL DEFAULT true
);

-- Lịch sử giá dịch vụ tại khu
CREATE TABLE service_price_configs (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
property_id bigint NOT NULL REFERENCES properties(id), service_item_id bigint NOT NULL REFERENCES service_items(id),
effective_from date NOT NULL, unit_price numeric(14,2) NOT NULL CHECK(unit_price>=0),
recorded_by bigint REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
UNIQUE(property_id,service_item_id,effective_from)
);

-- Đăng ký và số lượng theo khoảng, chế độ cả kỳ/chia ngày
CREATE TABLE contract_service_subscriptions (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
contract_id bigint NOT NULL REFERENCES contracts(id), service_item_id bigint NOT NULL REFERENCES service_items(id),
effective_from date NOT NULL, effective_to date, quantity integer NOT NULL DEFAULT 1 CHECK(quantity>0),
charge_mode varchar(20) NOT NULL DEFAULT 'PRORATED' CHECK(charge_mode IN ('PRORATED','FULL_PERIOD','ONE_TIME')),
recorded_by bigint REFERENCES users(id), CHECK(effective_to IS NULL OR effective_to>effective_from),
EXCLUDE USING gist(contract_id WITH =,service_item_id WITH =,daterange(effective_from,effective_to,'[)') WITH &&)
);

-- Công tơ vật lý; thay tạo mã mới
CREATE TABLE meters (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
room_id bigint NOT NULL REFERENCES rooms(id), service_item_id bigint NOT NULL REFERENCES service_items(id),
meter_code varchar(60) NOT NULL UNIQUE, installed_at timestamptz NOT NULL, retired_at timestamptz,
recorded_by bigint REFERENCES users(id), CHECK(retired_at IS NULL OR retired_at>installed_at),
EXCLUDE USING gist(room_id WITH =,service_item_id WITH =,tstzrange(installed_at,retired_at,'[)') WITH &&)
);

-- Điểm đo thực và chuỗi phiên bản sửa
CREATE TABLE meter_readings (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
meter_id bigint NOT NULL REFERENCES meters(id), observed_at timestamptz NOT NULL, reading_value numeric(14,3) NOT NULL CHECK(reading_value>=0),
time_precision varchar(30) NOT NULL DEFAULT 'EXACT' CHECK(time_precision IN ('EXACT','LEGACY_DAY_BOUNDARY')),
revision_no integer NOT NULL DEFAULT 1 CHECK(revision_no>0), supersedes_reading_id bigint UNIQUE REFERENCES meter_readings(id),
handover_id bigint REFERENCES handovers(id), recorded_by bigint NOT NULL REFERENCES users(id),
reason text, recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
UNIQUE(meter_id,observed_at,revision_no), CHECK(supersedes_reading_id IS NULL OR supersedes_reading_id<>id)
);

-- Khoảng đo giao trách nhiệm cho hợp đồng hoặc chủ nhà
CREATE TABLE consumption_segments (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
start_reading_id bigint NOT NULL REFERENCES meter_readings(id), end_reading_id bigint NOT NULL REFERENCES meter_readings(id),
contract_id bigint REFERENCES contracts(id), responsibility varchar(10) NOT NULL CHECK(responsibility IN ('TENANT','OWNER')),
supersedes_segment_id bigint UNIQUE REFERENCES consumption_segments(id), recorded_by bigint REFERENCES users(id),
created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(start_reading_id<>end_reading_id), CHECK((responsibility='TENANT')=(contract_id IS NOT NULL)),
CHECK(supersedes_segment_id IS NULL OR supersedes_segment_id<>id), UNIQUE(start_reading_id,end_reading_id)
);

-- Ngưỡng theo khu/phòng và dịch vụ, có hiệu lực
CREATE TABLE alert_policies (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
service_item_id bigint NOT NULL REFERENCES service_items(id), property_id bigint REFERENCES properties(id), room_id bigint REFERENCES rooms(id),
effective_from date NOT NULL, history_months smallint NOT NULL DEFAULT 3 CHECK(history_months BETWEEN 1 AND 12),
minimum_days integer NOT NULL DEFAULT 7 CHECK(minimum_days>0),
threshold_percentage numeric(9,2) NOT NULL DEFAULT 50 CHECK(threshold_percentage>0),
absolute_daily_threshold numeric(14,3) CHECK(absolute_daily_threshold>0),
CHECK(num_nonnulls(property_id,room_id)=1)
);

-- Lần đánh giá, baseline và xác nhận có căn cứ
CREATE TABLE consumption_alerts (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
segment_id bigint NOT NULL REFERENCES consumption_segments(id), policy_id bigint NOT NULL REFERENCES alert_policies(id),
supersedes_alert_id bigint UNIQUE REFERENCES consumption_alerts(id),
baseline_daily_average numeric(18,6), applied_threshold numeric(9,2) NOT NULL, method varchar(40) NOT NULL DEFAULT 'WEIGHTED_DAILY',
status varchar(30) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','CONFIRMED','DISMISSED','INSUFFICIENT_HISTORY','INCOMPARABLE')),
context_note text, checked_by bigint REFERENCES users(id), checked_at timestamptz,
created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(status NOT IN ('CONFIRMED','DISMISSED') OR (checked_by IS NOT NULL AND checked_at IS NOT NULL)),
CHECK(baseline_daily_average IS NULL OR baseline_daily_average>=0), UNIQUE(segment_id,policy_id)
);

-- Khoảng nào đã được dùng làm baseline
CREATE TABLE alert_baseline_sources (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
alert_id bigint NOT NULL REFERENCES consumption_alerts(id), source_segment_id bigint NOT NULL REFERENCES consumption_segments(id),
UNIQUE(alert_id,source_segment_id)
);

-- Lịch định kỳ, không ghi đè lịch sử lần đã làm
CREATE TABLE maintenance_schedules (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
asset_id bigint REFERENCES assets(id), room_id bigint REFERENCES rooms(id), property_id bigint REFERENCES properties(id),
title varchar(150) NOT NULL, interval_days integer NOT NULL CHECK(interval_days>0), next_due date NOT NULL,
is_active boolean NOT NULL DEFAULT true, created_by bigint REFERENCES users(id),
CHECK(num_nonnulls(asset_id,room_id,property_id)=1)
);

-- Sự cố theo vị trí, không bắt có hợp đồng
CREATE TABLE maintenance_requests (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
room_id bigint REFERENCES rooms(id), property_id bigint REFERENCES properties(id), asset_placement_id bigint REFERENCES asset_placements(id),
schedule_id bigint REFERENCES maintenance_schedules(id), scheduled_for date,
submitted_by bigint NOT NULL REFERENCES users(id), assigned_to bigint REFERENCES users(id),
title varchar(150) NOT NULL, description text NOT NULL,
priority varchar(20) NOT NULL DEFAULT 'NORMAL' CHECK(priority IN ('URGENT','NORMAL','LOW')),
status varchar(20) NOT NULL DEFAULT 'NEW' CHECK(status IN ('NEW','ACCEPTED','IN_PROGRESS','COMPLETED','CANCELLED')),
incident_type varchar(50) NOT NULL DEFAULT 'GENERAL', expected_date date NOT NULL,
created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
CHECK(num_nonnulls(room_id,property_id,asset_placement_id)=1),
CHECK((schedule_id IS NULL)=(scheduled_for IS NULL)), UNIQUE(schedule_id,scheduled_for)
);

-- Từng lần xử lý/giao việc/hoàn thành/tái phát
CREATE TABLE maintenance_events (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
request_id bigint NOT NULL REFERENCES maintenance_requests(id), action varchar(30) NOT NULL,
actor_id bigint NOT NULL REFERENCES users(id), note text NOT NULL DEFAULT '',
recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Chi phí thực tế, không đồng nhất bồi thường
CREATE TABLE maintenance_costs (
